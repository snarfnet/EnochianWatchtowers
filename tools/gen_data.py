#!/usr/bin/env python3
"""Generate App/Data/WatchtowerData.swift from the research files in tools/data/.

tablets.json        Golden Dawn grids (1587 Tabula Recensa letters) + variant readings per square
derived_names.json  every name derived by the rules in rules.md, with its squares and how many
                    published sources print the same spelling
glossary.json       term explanations (en / ja)
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
OUT = os.path.join(os.path.dirname(HERE), "App", "Data", "WatchtowerData.swift")

SOURCE_LABELS = {
    "DEE": "Dee, Sloane MS 3191",
    "TFR": "Casaubon, A True & Faithful Relation (1659)",
    "BOOKH": "Golden Dawn, Book H",
    "GDCONS": "Golden Dawn, Consecration ritual",
    "GDCONS_pron": "Golden Dawn, Consecration ritual",
    "CROWLEY": "Crowley, Liber Chanokh (1912)",
    "KONDOR": "kondor.de",
    "ROWE": "B. Rowe, Enochian Temples (1992)",
    "ROWE_SENIORS": "B. Rowe, The Book of the Seniors",
    "AZ0TH": "Az0th, Recensa recomputation",
}
NOTE_LABELS = {
    "gdBookH": "Golden Dawn, Book H",
    "crowleyPlateIII_1912": "Crowley, Plate III (1912)",
    "dee1584_kondor": "Dee 1584 table",
    "recensa1587_peterson": "1587 Recensa (Peterson)",
    "dee1584_TFR1659": "Dee 1584 table (Casaubon 1659)",
}
SUB_ORDER = ["Air", "Water", "Earth", "Fire"]   # top-left, top-right, bottom-left, bottom-right


def s(x):
    return json.dumps(x, ensure_ascii=False)


def cells(c):
    return "[" + ", ".join(f"C({r}, {k})" for r, k in c) + "]"


def name_entry(category, o, sub="nil", order=None, planet=None, prefix=None):
    variants = []
    for src, sp in o.get("publishedDifferent", {}).items():
        if src == "GDCONS_pron":
            continue
        variants.append(f"V({s(SOURCE_LABELS.get(src, src))}, {s(sp.replace('|', ' / '))})")
    matches = sorted({SOURCE_LABELS.get(m, m) for m in o.get("publishedMatches", []) if m != "AZ0TH"})
    cl = o["cells"] if order is None else order
    return (f"        N(.{category}, sub: {sub}, name: {s(o['derived'])}, cells: {cells(cl)}, "
            f"status: .{o['status']}, sources: [{', '.join(s(m) for m in matches)}], "
            f"variants: [{', '.join(variants)}]"
            + (f", planet: .{planet.lower()}" if planet else "")
            + (f", prefix: {s(prefix)}" if prefix else "")
            + ")")


def main():
    tablets = json.load(open(os.path.join(DATA, "tablets.json"), encoding="utf-8"))["goldenDawn"]
    names = json.load(open(os.path.join(DATA, "derived_names.json"), encoding="utf-8"))["names"]
    glossary = json.load(open(os.path.join(DATA, "glossary.json"), encoding="utf-8"))

    out = ["// Generated by tools/gen_data.py from tools/data/*.json. Do not edit by hand.", "",
           "extension WatchtowerData {"]
    out.append("    static let tablets: [Tablet] = [")
    for el in SUB_ORDER:
        t = tablets["tablets"][el]
        n = names[el]
        rows = ", ".join(s(r) for r in t["rows"])
        notes = []
        for cn in t.get("cellNotes", []):
            readings = cn.get("otherReadings") or {k: v for k, v in cn.items() if k.startswith("recensa")}
            parts = [f"V({s(NOTE_LABELS.get(k, k))}, {s(v.upper())})" for k, v in readings.items()]
            notes.append(f"CellNote(cell: C({cn['row']}, {cn['col']}), readings: [{', '.join(parts)}])")
        entries = []
        for h in n["threeHolyNames"]:
            entries.append(name_entry("holyName", h))
        entries.append(name_entry("king", n["greatKing"]))
        for key, sen in n["sixSeniors"].items():
            entries.append(name_entry("senior", sen, planet=sen.get("planetGD")))
        for i, sub_el in enumerate(SUB_ORDER):
            sa = n["subAngles"][f"{sub_el} of {el}"]
            entries.append(name_entry("calling", sa["calvaryCross_vertical_6_callingName"], sub=str(i)))
            entries.append(name_entry("commanding", sa["calvaryCross_horizontal_5_commandingName"], sub=str(i)))
            ruler = sa["kerubicRulingName_prefixed"]
            entries.append(name_entry("kerubicRuler", ruler, sub=str(i), prefix=ruler["derived"][0]))
            for k, ker in enumerate(sa["kerubicAngels"]):
                c = ker["cells"]
                entries.append(name_entry("kerubic", ker, sub=str(i), order=c[k:] + c[:k]))
            for j, sv in enumerate(sa["servientAngels"]):
                entries.append(name_entry("servient", sv, sub=str(i)))
            for sv in sa["servientAngels_prefixed"]:
                entries.append(name_entry("servientPrefixed", sv, sub=str(i), prefix=sv["derived"][0]))
        out.append(f"        Tablet(element: .{el.lower()}, union: {s(t['tabletOfUnionLine'])}, "
                   f"rows: [{rows}],")
        out.append(f"               notes: [{', '.join(notes)}],")
        out.append("               names: [")
        out.append(",\n".join("    " + e for e in entries))
        out.append("               ]),")
    out.append("    ]")
    out.append("")
    out.append("    static let glossary: [GlossaryTerm] = [")
    for key, g in glossary.items():
        out.append(f"        GlossaryTerm(key: {s(key)}, term: {s(g['term'])}, termJa: {s(g['termJa'])}, "
                   f"en: {s(g['en'])}, ja: {s(g['ja'])}),")
    out.append("    ]")
    out.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
